'use strict';
const assert=require('node:assert/strict');
const Module=require('node:module');
const load=Module._load;
Module._load=function(r){if(r==='obsidian')return {Plugin:class{},ItemView:class{},Modal:class{},Setting:class{},Notice:class{},Menu:class{},PluginSettingTab:class{},TFile:class{}};return load.apply(this,arguments);};
const t=require('../main.js').__test;
const proj=t.makeExample();
const file={path:'CueFlow/test.md'};
let document='读者自由编辑的项目前言\n\n'+t.safeMarkdown(proj)+'\n结尾不会丢失';
const outputs=[];
const app={vault:{read:async()=>document, modify:async(f,body)=>{assert.equal(f,file);document=body;},getAbstractFileByPath:()=>null,create:async(p,body)=>{outputs.push({p,body});return {path:p};}}};
const view=Object.create(t.CueFlowView.prototype);
Object.assign(view,{app,file,project:proj,saveChain:Promise.resolve(),plugin:{settings:{folder:'CueFlow'}},scale:3});
(async()=>{
  proj.cues[0].name='新开场 <安全> & 说明';
  await view.saveNow();
  assert.ok(document.startsWith('读者自由编辑的项目前言'));
  assert.ok(document.endsWith('结尾不会丢失'));
  assert.equal(JSON.parse(document.match(/```cueflow\n([\s\S]*?)\n```/)[1]).cues[0].name, '新开场 <安全> & 说明');
  await view.exportCSV();
  await view.exportSVG();
  assert.equal(outputs.length,2);
  assert.ok(outputs[0].body.startsWith('\ufeff'));
  assert.ok(outputs[0].body.includes('"分组","角色/设备"'));
  assert.ok(outputs[0].body.includes('"执行人员","导播"'));
  assert.ok(outputs[1].body.includes('执行人员 · 4'));
  assert.ok(outputs[1].body.includes('设备 · 2'));
  assert.ok(outputs[1].body.includes('新开场 &lt;安全&gt; &amp; 说明'));
  console.log('Storage/export PASS (Markdown preservation, CSV, SVG and escaping)');
})().catch(e=>{console.error(e);process.exitCode=1;});
